import type {
  StrategyQuestion,
  StrategySkill,
  TrapExercise,
} from "./strategy-types";
type Row = [string, string, string, string[], string, string?];
const bank: StrategyQuestion[] = [];
function add(id: string, patternId: string, skill: StrategySkill, rows: Row[]) {
  for (const [
    i,
    [source, text, answer, alternatives, evidence, trap],
  ] of rows.entries()) {
    const options = [answer, ...alternatives].sort();
    bank.push({
      id: `${id}-${i + 1}`,
      strategyId: id,
      patternId,
      skill,
      phase: i < 5 ? "guided" : i < 15 ? "independent" : "timed",
      source,
      text,
      answer,
      options,
      evidence,
      trap: trap || "Unsupported interpretation",
      reasoning: [
        `Identify what is asked: ${text}`,
        `Locate the deciding evidence: ${evidence}`,
        `Choose only the response supported by that evidence: ${answer}`,
      ],
      wrong: Object.fromEntries(
        alternatives.map((a) => [
          a,
          `“${a}” does not match the deciding evidence: ${evidence}. ${trap || "Do not add, reverse or exaggerate the stated relationship."}`,
        ]),
      ),
      hint:
        skill === "Reading"
          ? "Compare the exact scope of the statement with the source. Absence of information is different from contradiction."
          : skill === "Listening"
            ? "Listen through the final decision. A mentioned alternative can be rejected or corrected."
            : "Check the requirement and choose the option that addresses it directly.",
      burmese:
        "စာသားထဲက အထောက်အထားကို အရင်ရှာပါ။ ဖော်ပြထားသည့် အချက်ကိုသာ အသုံးပြုပြီး မိမိထင်မြင်ချက်ကို မထည့်ပါနှင့်။",
      ...(skill === "Listening"
        ? { audio: `/audio/strategy/${id}-${i + 1}.wav` }
        : {}),
    });
  }
}
